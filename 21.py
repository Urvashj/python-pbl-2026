print("Using break:") 

 

for i in range(1, 6): 

  if i == 4: 

      break 

  print(i) 

 

print("Using continue:") 

 

for i in range(1, 6): 

  if i == 3: 

      continue 

  print(i) 

 

print("Using pass:") 

 

for i in range(1, 4): 

  if i == 2: 

      pass 

  print(i) 